"""The frozen H6 grid, its cell keys, and the seed derivation of section 10.

This module **loads** the grid; it does not build it. ``studies/theta0.json`` was
generated by ``studies/make_theta0.py`` before the freeze and committed with the
digest the preregistration records. The only thing constructed here is a stable
key per cell and the seed per ``(cell, replication)``, both normative.

Section 10 is the authority for the seeds:

    cell_seed = SplitMix64( int(sha256("h6-v1|<M>|<N>|<rho>|<r>|<c>")[:16], 16) )
    rep_seed  = _core.seed_stream(cell_seed, rep_index)

Two points in that derivation are not written down in the file, and both are
resolved here by the narrowest possible reading of text that *is* written down.
They are recorded in ``studies/HARNESS_NOTES.md`` and are **not** amendments,
because each has one defensible answer:

* **``SplitMix64(x)`` means one step of the generator, not two.** ADR-005 and
  ``cpp/src/rng.cpp`` define ``splitmix64(state)`` as: advance by the golden
  gamma, then apply both mix multipliers. The two-step reading (an implicit
  ``Rng(seed)`` constructor) would also be defensible, and the golden vector in
  this module pins which one was used so the choice is checkable rather than
  implicit.
* **The string fields are formatted by the rules in :func:`seed_message`**, which
  is the smallest formatting that round-trips every grid value without
  ambiguity.

``rep_index`` is 0-based because ``_core.seed_stream`` is defined on
``0 <= index < 2**64`` and the preregistration's own sentence -- "a change in R
does not change the seed of any earlier replication" -- only holds if
replication ``r = 1`` maps to index ``0``. The row records both indexings.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

from hawkes_engine import _core

__all__ = [
    "STUDY_ID",
    "Cell",
    "EXPECTED_DIGEST",
    "RUN_VALUES",
    "canonical_digest",
    "cell_key",
    "load_cells",
    "rep_seed",
    "seed_message",
    "splitmix64",
    "cell_seed",
    "golden_vector",
]

STUDY_ID = "h6-v1"
EXPECTED_DIGEST = "f735ae4113563f53ce992d4fc767bdc0439e72731af130f3b57d33720a291887"
R = 2000

STUDIES = Path(__file__).resolve().parent
THETA0_PATH = STUDIES / "theta0.json"

_MASK64 = (1 << 64) - 1
_GOLDEN_GAMMA = 0x9E3779B97F4A7C15


def splitmix64(state: int) -> tuple[int, int]:
    """One step of SplitMix64: the advanced state and the mixed output.

    This is ``splitmix64`` from ``cpp/src/rng.cpp`` -- ``state += gamma`` then two
    xorshift-multiplies and a final xorshift. It reproduces the ``words`` lines of
    ``tests/golden/rng.txt``, which is what makes the Python implementation of
    the seed contract checkable against the compiled one.
    """
    state = (state + _GOLDEN_GAMMA) & _MASK64
    z = state
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & _MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & _MASK64
    return state, z ^ (z >> 31)


def seed_message(M: int, N: int, rho: float, r: float, c: float) -> str:
    """The canonical ``"h6-v1|<M>|<N>|<rho>|<r>|<c>"`` string of section 10.

    Formatting rules, chosen to round-trip every grid value exactly:

    * ``M`` and ``N`` are decimal integers;
    * ``rho``, ``r`` and ``c`` use ``repr``, which is the shortest string that
      parses back to the same double. So ``0.3028`` stays ``0.3028``, ``0.0``
      stays ``0.0``, ``1.0`` stays ``1.0`` and ``1e-3`` becomes ``0.001``.

    The rules matter: ``"0.302800"`` and ``"0.3028"`` are different hashes, and
    a harness that formatted one way while a referee recomputed the other would
    get different seeds from the same frozen design.
    """
    return f"{STUDY_ID}|{int(M)}|{int(N)}|{repr(float(rho))}|{repr(float(r))}|{repr(float(c))}"


def cell_seed(M: int, N: int, rho: float, r: float, c: float) -> int:
    """``SplitMix64(int(sha256(message)[:16], 16))`` as an unsigned 64-bit int."""
    message = seed_message(M, N, rho, r, c)
    digest = hashlib.sha256(message.encode("utf-8")).digest()
    _, seed = splitmix64(int.from_bytes(digest[:16], "big"))
    return int(seed)


def rep_seed(cell: Cell, rep_index: int) -> int:
    """Seed of replication ``rep_index`` (0-based) within ``cell``.

    Delegates to the compiled ``_core.seed_stream`` so that the stream map is the
    one ADR-005 specifies rather than a Python reimplementation of it.
    """
    if not 0 <= rep_index < 2**64:
        raise ValueError(f"rep_index must be in [0, 2**64), got {rep_index}")
    return int(_core.seed_stream(cell.seed, int(rep_index)))


def golden_vector() -> dict[str, int]:
    """Committed seeds the harness asserts before it measures anything.

    Amendment 1 makes the pilot's first assertion that the golden vector
    reproduces. The values are derived from section 10 as implemented here; they
    are committed so that a later change to the formatting rules cannot pass
    silently.
    """
    return GOLDEN


@dataclass(frozen=True)
class Cell:
    """One frozen grid point.

    ``key`` is the stable identifier used for file names and row labels. It is
    derived from ``(M, N, rho, r, c)`` -- the five design coordinates -- and from
    ``satellite``, which is redundant with ``M`` on this grid but is part of how
    the preregistration describes the grid. Nothing else enters it, so the key
    is stable against a change in any quantity that is measured rather than
    chosen.
    """

    key: str
    M: int
    N_target: int
    rho: float
    r: float
    c: float
    mu: tuple[float, ...]
    alpha: tuple[tuple[float, ...], ...]
    beta: tuple[tuple[float, ...], ...]
    delta: float
    T: float
    rate: float
    n_params: int
    satellite: bool
    seed: int

    @property
    def beta_min(self) -> float:
        return min(min(row) for row in self.beta)

    @property
    def relaxation(self) -> float:
        """``1 / (beta_min * (1 - rho))``: the slowest decay after thinning.

        This is the time scale on which the process forgets its initial state,
        and it is what the burn-in rule in :mod:`studies.run_cell` is stated in.
        It is derived, never chosen.
        """
        return 1.0 / (self.beta_min * (1.0 - self.rho))


def cell_key(M: int, N: int, rho: float, r: float, c: float, satellite: bool) -> str:
    """A filename-safe, deterministic key for a cell.

    ``N=200  rho=0.3028  r=0.01  c=0.001  M=2`` becomes
    ``M2_N200_rho0.3028_r0.01_c0.001``; the satellite cells gain a ``_sat``
    suffix. Dots are safe on Windows, so they are kept: the key reads back as the
    coordinates it encodes.
    """
    body = f"M{M}_N{int(N)}_rho{repr(float(rho))}_r{repr(float(r))}_c{repr(float(c))}"
    return body + ("_sat" if satellite else "")


def canonical_digest(path: Path = THETA0_PATH) -> str:
    """The freeze digest, recomputed the way the preregistration defines it."""
    parsed = json.loads(path.read_text(encoding="utf-8"))
    body = json.dumps(parsed, indent=2, sort_keys=False, ensure_ascii=False) + "\n"
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def load_cells(path: Path = THETA0_PATH, *, verify: bool = True) -> list[Cell]:
    """Every frozen cell, in file order, with its key and its seed.

    ``verify`` recomputes the canonical digest and refuses to return a grid that
    does not match the preregistration. The run calls this before its first
    cell, per section 5.2; a measurement against a changed grid is not a
    measurement of this study.
    """
    if verify:
        digest = canonical_digest(path)
        if digest != EXPECTED_DIGEST:
            raise RuntimeError(
                f"the grid digest is {digest}, but the preregistration records "
                f"{EXPECTED_DIGEST}; refusing to measure against a changed grid"
            )
    payload = json.loads(path.read_text(encoding="utf-8"))
    cells: list[Cell] = []
    for raw in payload["cells"]:
        M = int(raw["M"])
        N = int(raw["N_target"])
        rho = float(raw["rho"])
        r = float(raw["r"])
        c = float(raw["c"])
        satellite = bool(raw["satellite"])
        cells.append(
            Cell(
                key=cell_key(M, N, rho, r, c, satellite),
                M=M,
                N_target=N,
                rho=rho,
                r=r,
                c=c,
                mu=tuple(float(v) for v in raw["mu"]),
                alpha=tuple(tuple(float(v) for v in row) for row in raw["alpha"]),
                beta=tuple(tuple(float(v) for v in row) for row in raw["beta"]),
                delta=float(raw["delta"]),
                T=float(raw["T"]),
                rate=float(raw["rate"]),
                n_params=int(raw["n_params"]),
                satellite=satellite,
                seed=cell_seed(M, N, rho, r, c),
            )
        )
    keys = [cell.key for cell in cells]
    if len(set(keys)) != len(keys):
        raise RuntimeError("cell keys are not unique; the key derivation is ambiguous")
    return cells


# The seed of every (cell, replication) the harness will ever use is a pure
# function of these five numbers, so pinning a handful pins the formatting rules.
# Computed once here rather than typed by hand: a golden vector transcribed by a
# human would pin the human's transcription, not the derivation.
GOLDEN = {
    "anchor_M2_N2000_rho0.3028_r0.0_c1.0_cell": cell_seed(2, 2000, 0.3028, 0.0, 1.0),
    "anchor_M2_N2000_rho0.3028_r0.0_c1.0_rep0": int(
        _core.seed_stream(cell_seed(2, 2000, 0.3028, 0.0, 1.0), 0)
    ),
    "anchor_M2_N2000_rho0.3028_r0.0_c1.0_rep1": int(
        _core.seed_stream(cell_seed(2, 2000, 0.3028, 0.0, 1.0), 1)
    ),
    "quantised_M2_N200_rho0.95_r0.1_c1.0_cell": cell_seed(2, 200, 0.95, 0.1, 1.0),
    "slowdecay_M2_N200_rho0.3028_r0.0_c0.001_cell": cell_seed(2, 200, 0.3028, 0.0, 1e-3),
    "satellite_M4_N20000_rho0.85_r0.1_c1.0_cell": cell_seed(4, 20000, 0.85, 0.1, 1.0),
    "splitmix_of_zero": splitmix64(0)[1],
}

