def _git(*args: str) -> str:
    try:
        return subprocess.run(
            ["git", *args], cwd=REPO, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):  # pragma: no cover - environment
        return "unknown"


def _data_commit() -> str:
    """The commit the numbers in this document were produced from.

    Read from the analysis output, not from git. Two reasons:

    * Embedding ``HEAD`` makes the file stale the moment it is committed, and the
      check that guards it then fails on every clean checkout.
    * Asking git for the last commit touching the study outputs gives a different
      answer under a shallow checkout, which is what CI does. A generator whose
      output depends on history depth cannot be checked for staleness at all.

    ``provenance.analysis_commit`` is written by the analysis run itself, so it is
    a property of the committed data and every checkout agrees on it.
    """
    try:
        payload = json.loads(H6_HYP.read_text(encoding="utf-8"))
        commit = payload["provenance"]["analysis_commit"]
    except (OSError, KeyError, ValueError):  # pragma: no cover - environment
        return "unknown"
    return str(commit)


def tex_num(value: float, digits: int = 3) -> str:
    """A number in the paper's house style: plain digits, no scientific noise.

    Below 1e-3 and above 1e4 it switches to scientific notation, because a
    column of ``0.00000123`` is unreadable in print. The exponent is written as
    ``\\times 10^{n}`` rather than ``e-06``, which is not a number in typeset prose.
    """
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    if value == math.inf:
        return r"$\infty$"
    if value != 0 and (abs(value) >= 1e4 or abs(value) < 10 ** (-digits)):
        mantissa, exponent = f"{value:.{max(digits - 1, 1)}e}".split("e")
        return rf"${mantissa}\times 10^{{{int(exponent)}}}$"
    return f"{value:.{digits}f}"


def tex_pm(estimate: float, se: float, digits: int = 3) -> str:
    """``estimate +/- se`` as the paper writes it, with a typeset plus-minus."""
    return rf"${tex_num(estimate, digits)} \pm {tex_num(se, digits)}$"


def tex_p(p: float) -> str:
    if p == 0.0:
        return r"$<10^{-300}$"
    if p < 1e-4:
        return rf"${p:.1e}$".replace("e-", r"\times 10^{-").replace("$", "$", 1) + "}$"
    return f"{p:.3g}"


def _f(value: Any) -> float:
    if value in ("", None):
        return math.nan
    return float(value)


def thousands(value: int) -> str:
    """A count with a thin-space thousands separator TeX can typeset.

    ``f"{n:,}"`` is Python's comma, and inside a macro argument TeX parses ``{,}``
    as a group rather than a comma, so the naive replacement renders ``6{,}000``
    as "6000" with a missing digit grouping. Splitting the integer into groups of
    three and joining with ``{,}`` is what actually produces "6,000" in the PDF.
    """
    digits = str(int(value))
    if len(digits) <= 3:
        return digits
    groups: list[str] = []
    while digits:
        groups.insert(0, digits[-3:])
        digits = digits[:-3]
    return r"{,}".join(groups)


def macro(name: str, value: str) -> str:
    if not name.isalpha():
        raise ValueError(
            f"macro name {name!r} is not letters only. A TeX control word ends at the "
            "first non-letter, so a name like 'Hsix61Label' is read as \\Hsix followed "
            "by the text '61Label', which lands in the preamble and fails the compile."
        )
    return rf"\newcommand{{\{name}}}{{{value}}}"


# -------------------------------------------------------------- sw-v1 numbers


def sw_macros() -> list[str]:
    """The sandwich study's figures, read from its committed estimands.

    Every value here comes from ``studies/results/sandwich/estimands.json``,
    which is written by ``studies/analyze_sandwich.py`` from the study's rows. The
    cells are selected by their frozen keys rather than by shape, so a change to
    the study's population cannot silently change what these macros report.
    """
    est = json.loads((SANDWICH / "estimands.json").read_text(encoding="utf-8"))
    primary = [
        "M2_N2000_rho0.3028_r0.0_c1.0",
        "M2_N2000_rho0.6_r0.0_c1.0",
        "M2_N2000_rho0.85_r0.0_c1.0",
        "M2_N2000_rho0.95_r0.0_c1.0",
        "M2_N10000_rho0.95_r0.0_c1.0",
    ]
    g = [est[key]["beta"]["g"] for key in primary]
    g_low, g_high = min(g), max(g)
    # sqrt(J/I) is how much the sandwich can move the interval, relative to the
    # inverse Hessian. Bounded on both sides so the paper cannot overstate either.
    factor = max(g_high**0.5, g_low**-0.5)
    return [
        macro("SwCells", str(len(est))),
        macro("SwReplications", str(next(iter(est.values()))["replications"])),
        macro("SwGRatioLow", tex_num(g_low)),
        macro("SwGRatioHigh", tex_num(g_high)),
        macro("SwMaxFactor", tex_num(factor)),
    ]


