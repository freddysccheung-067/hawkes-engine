"""Generate ``paper/main.tex`` and its generated fragments. No number is typed by hand.

Every quantity that appears in the paper is emitted here as a LaTeX macro
definition or a table body, into ``paper/generated/``. ``paper/main.tex`` carries
the prose and ``\\input``s those files, so a change to the analysis changes the
paper when this script is re-run and a paper build can never silently hold a
stale number.

    python -m studies.make_paper_tex          # write the fragments and main.tex
    python -m studies.make_paper_tex --check  # fail if the tree is not up to date

Sources, all committed:

``studies/results/analysis/``       the H6 study (``hypotheses.json``,
                                    ``cells.csv``, ``blocks.csv``, provenance);
``studies/results/auto/analysis/``  the auto-v1 study;
``studies/results/sandwich/``       the sw-v1 study (``estimands.json``, ``report.txt``);
``studies/RUN_REPORT.md``           the grid's wall clock and replication count;
``benchmarks/results/``             the capability table's timing figures;
``data/trust/v1_excitation_only.csv`` the shipped map.

The Markdown draft (``paper/draft.md``, generated by ``studies/make_paper.py``)
stays the readable source of prose. This script generates the submission form.
"""

