def grid_table() -> str:
    blocks = {(r["cell"], r["block"]): r for r in _read_csv(ANALYSIS / "blocks.csv")}
    cells = [
        r
        for r in _read_csv(ANALYSIS / "cells.csv")
        if r["M"] == "2" and r["c"] == "1.0" and r["r"] == "0.0"
    ]
    cells.sort(key=lambda r: (int(r["N"]), float(r["rho"])))
    lines = [
        # Seven columns of estimate +/- MC SE overflow a 6.5-inch text block at
        # 11pt, measured on the first real typeset: 78pt too wide. Small type and
        # tight column separation bring it inside the margin without changing what
        # is reported.
        r"{\small\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{rrrrrrr}",
        r"\toprule",
        r"$N$ & $\rho$ & coverage $\mu$ & coverage $\alpha$ & coverage $\beta$ "
        r"& $q_\mu$ & $q_\beta$ \\",
        r"\midrule",
    ]
    for c in cells:
        key = c["cell"]
        mu, al, be = (blocks[(key, b)] for b in ("mu", "alpha", "beta"))
        lines.append(
            f"{int(c['N']):,}".replace(",", "{,}") + f" & {c['rho']} & "
            f"{tex_pm(float(mu['cov_all']), float(mu['se_cov_all']))} & "
            f"{tex_pm(float(al['cov_all']), float(al['se_cov_all']))} & "
            f"{tex_pm(float(be['cov_all']), float(be['se_cov_all']))} & "
            f"{tex_pm(float(mu['q']), float(mu['se_q_boot']))} & "
            f"{tex_pm(float(be['q']), float(be['se_q_boot']))} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}}"]
    return "\n".join(lines) + "\n"


def _drift_count() -> int:
    """Replications at the anchor whose nearest cell was in another rho column.

    Read from the committed analysis, not from the raw rows: the raw rows are
    gitignored and only the table generated from them is in the repository.
    """
    payload = json.loads(AUTO_HYP.read_text(encoding="utf-8"))
    low = next(c for c in payload["cells"] if c["cell"] == "M2_N2000_rho0.3028_r0.0_c1.0")
    return int(low.get("nearest_elsewhere", 0))


def _max_distance() -> float:
    payload = json.loads(AUTO_HYP.read_text(encoding="utf-8"))
    low = next(c for c in payload["cells"] if c["cell"] == "M2_N2000_rho0.3028_r0.0_c1.0")
    return float(low.get("distance_max", float("nan")))


