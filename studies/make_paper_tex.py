def copy_figures() -> list[Path]:
    """Copy the study figures beside the paper, so the .tex tree builds alone.

    arXiv takes one archive; a document that inputs ``../../studies/figures/x.pdf``
    would not build from that archive. The copies are byte-identical to the
    generated originals, which are the ones `make_figures` writes.
    """
    source_dir = REPO / "studies" / "figures"
    target = PAPER / "figures"
    target.mkdir(parents=True, exist_ok=True)
    copied: list[Path] = []
    for name in FIGURE_SOURCES:
        src = source_dir / name
        if not src.exists():
            continue
        dst = target / name
        if not dst.exists() or dst.read_bytes() != src.read_bytes():
            dst.write_bytes(src.read_bytes())
        copied.append(dst)
    return copied


def write_tree() -> list[Path]:
    GENERATED.mkdir(parents=True, exist_ok=True)
    macros = h6_macros() + theory_macros() + auto_macros() + cost_macros() + sw_macros()
    head = _data_commit()
    # The abstract's length is a submission requirement, so it is reported rather
    # than estimated. Macro invocations count as their expansion would read: a
    # word is a whitespace-separated token, and a macro is one token.
    abstract_words = len(re.sub(r"\\[A-Za-z]+", "X", SECTIONS["abstract"]).split())
    macros.append(macro("AbstractWords", str(abstract_words)))
    written: list[Path] = []
    for name, body in SECTIONS.items():
        path = GENERATED / f"{name}.tex"
        path.write_text(
            body.strip().replace("%%HEAD%%", head) + "\n", encoding="utf-8", newline="\n"
        )
        written.append(path)
    for name, body in (
        ("table_hypotheses", hypothesis_table()),
        ("table_grid", grid_table()),
        ("table_auto", auto_table()),
    ):
        path = GENERATED / f"{name}.tex"
        path.write_text(body, encoding="utf-8", newline="\n")
        written.append(path)
    main = PAPER / "main.tex"
    main.write_text(build_main(macros).replace("%%HEAD%%", head), encoding="utf-8", newline="\n")
    written.append(main)
    written.extend(copy_figures())
    return written


def check_tree() -> int:
    """Fail when the committed tree differs from what the sources now produce."""
    before = {}
    for path in [*GENERATED.glob("*.tex"), PAPER / "main.tex"]:
        if path.exists():
            before[path] = path.read_text(encoding="utf-8")
    write_tree()
    stale = [
        str(path.relative_to(REPO))
        for path, text in before.items()
        if path.exists() and path.read_text(encoding="utf-8") != text
    ]
    if stale:
        print("stale generated files: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("generated tree is up to date")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        return check_tree()
    written = write_tree()
    for path in written:
        print(f"wrote {path.relative_to(REPO)}")
    return 0


