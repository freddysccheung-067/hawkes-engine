"""Freeze the theta_0 sets for every H6 grid cell.

Run once, before any measurement, so that the configurations a referee would
recompute are committed rather than reconstructed.  Writes studies/theta0.json
and prints its SHA-256, which the preregistration records.

The construction is the one stated in docs/preregistration.md section 5.1:

    b_a   = [[1.0, 1.2], [1.1, 1.3]]                  the H3 decay
    G_H3  = ([[0.20, 0.10], [0.15, 0.25]] / b_a)      spectral radius 0.3028236...
    G_0   = G_H3 / rho(G_H3)                          spectral radius 1

    beta  = c * b_a
    alpha = rho * G_0 * beta        (elementwise in the product)

so alpha / beta = rho * G_0 has spectral radius rho and is independent of c.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
from hawkes_engine import _core

MU = np.array([0.5, 0.3])
B_A = np.array([[1.0, 1.2], [1.1, 1.3]])
A_H3 = np.array([[0.20, 0.10], [0.15, 0.25]])
RHO_H3 = float(_core.spectral_radius(MU, A_H3, B_A))

N_VALUES = (200, 1000, 2000, 10000, 50000)
RHO_VALUES = (0.3028, 0.60, 0.85, 0.95)
R_VALUES = (0.0, 0.01, 0.1)
C_VALUES = (1.0, 1e-3)

N_SAT = (2000, 20000)
RHO_SAT = (0.3028, 0.85)
R_SAT = (0.0, 0.1)

M_SAT = 4
SAT_MU = np.array([0.4, 0.3, 0.5, 0.35])
_sat_rng = np.random.default_rng(4242)
SAT_GAMMA = _sat_rng.uniform(0.3, 0.9, (M_SAT, M_SAT))
SAT_BETA = _sat_rng.uniform(1.0, 2.0, (M_SAT, M_SAT))
_sat_alpha_unscaled = SAT_GAMMA * SAT_BETA
_sat_radius = _core.spectral_radius(SAT_MU, _sat_alpha_unscaled, SAT_BETA)


def g0_for(a_h3: np.ndarray, b_a: np.ndarray, mu: np.ndarray) -> np.ndarray:
    """The unit-spectral-radius branching matrix of a reference configuration."""
    g_h3 = a_h3 / b_a
    return g_h3 / _core.spectral_radius(mu, a_h3, b_a)


def rate_of(mu: np.ndarray, alpha: np.ndarray, beta: np.ndarray) -> float:
    return float(_core.stationary_mean(mu, alpha, beta).sum())


def cell(M, N, rho, r, c, mu, b_a, g0, *, satellite=False):
    beta = c * b_a
    alpha = rho * g0 * beta
    radius = float(_core.spectral_radius(mu, alpha, beta))
    rate = rate_of(mu, alpha, beta)
    return {
        "M": M,
        "N_target": N,
        "rho": rho,
        "r": r,
        "c": c,
        "mu": np.round(mu, 12).tolist(),
        "alpha": np.round(alpha, 12).tolist(),
        "beta": np.round(beta, 12).tolist(),
        "delta": (r / float(np.min(beta))) if r > 0 else 0.0,
        "T": N / rate,
        "rho_check": radius,
        "rate": rate,
        "n_params": M + 2 * M * M,
        "satellite": satellite,
    }


cells = []
g0 = g0_for(A_H3, B_A, MU)
for N in N_VALUES:
    for rho in RHO_VALUES:
        for r in R_VALUES:
            for c in C_VALUES:
                cells.append(cell(2, N, rho, r, c, MU, B_A, g0))

sat_g0 = g0_for(SAT_GAMMA * SAT_BETA / _sat_radius, SAT_BETA, SAT_MU)
for N in N_SAT:
    for rho in RHO_SAT:
        for r in R_SAT:
            cells.append(cell(M_SAT, N, rho, r, 1.0, SAT_MU, SAT_BETA, sat_g0, satellite=True))

# Every cell must land on the rho it claims, and on the rate the design assumes.
for c in cells:
    if abs(c["rho_check"] - c["rho"]) > 1e-9:
        raise SystemExit(f"rho mismatch: asked {c['rho']}, got {c['rho_check']}")

payload = {
    "study_id": "h6-v1",
    "note": "theta_0 for every H6 cell, generated by studies/make_theta0.py",
    "constants": {
        "rho_H3": RHO_H3,
        "mu": MU.tolist(),
        "beta_H3": B_A.tolist(),
        "alpha_H3": A_H3.tolist(),
        "G0": np.round(g0, 12).tolist(),
        "satellite_mu": SAT_MU.tolist(),
        "satellite_beta": np.round(SAT_BETA, 12).tolist(),
        "satellite_G0": np.round(sat_g0, 12).tolist(),
    },
    "n_cells": len(cells),
    "cells": cells,
}

out = Path(__file__).with_name("theta0.json")
# A byte hash of the file is not stable here: git normalises line endings on
# checkout, so the same grid hashes differently in the working tree than in the
# object store. The digest recorded in the preregistration is therefore
# canonical: re-serialise the parsed payload with fixed arguments and hash that.
# It depends on the grid and nothing else.
data = (json.dumps(payload, indent=2, sort_keys=False) + "\n").encode("utf-8")
with out.open("wb") as handle:
    handle.write(data)


def canonical_digest(path: Path) -> str:
    """SHA-256 of the grid's canonical form, independent of line endings."""
    parsed = json.loads(path.read_text(encoding="utf-8"))
    body = json.dumps(parsed, indent=2, sort_keys=False, ensure_ascii=False) + "\n"
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


digest = canonical_digest(out)
print(f"cells written: {len(cells)}")
print(f"rho_H3       : {RHO_H3:.12f}")
print(f"canonical    : {digest}")
print(f"path         : {out}")
