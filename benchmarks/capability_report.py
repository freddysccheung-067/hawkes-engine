"""Phase 4 of H7: assemble ``capability_<date>.md`` from the committed CSVs.

Nothing here measures anything. Every number in the report is read from a file
written by one of the capability scripts or by the earlier benchmark scripts,
and the derivations (budgets, shares, ratios) are computed below, so the report
can be regenerated and diffed.

Usage:
    python benchmarks/capability_report.py [--date 2026-10-21]
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from benchmarks._common import RESULTS, today  # noqa: E402

# Labelling rule for the dominant term of a wall-grid row. The Hessian pass is
# timed separately and the optimiser is the remainder; the optimiser is called
# iteration-bound when it needed more than ITER_BOUND iterations.
HESSIAN_SHARE = 0.40
ITER_BOUND = 500
GIB = 2**30
MIB = 2**20


def rows(path: Path) -> list[dict[str, str]]:
    lines = [ln for ln in path.read_text(encoding="utf-8").splitlines() if not ln.startswith("#")]
    return list(csv.DictReader(lines))


def header(path: Path) -> list[str]:
    return [ln[2:] for ln in path.read_text(encoding="utf-8").splitlines() if ln.startswith("# ")]


def fmt_s(s: float) -> str:
    if s < 100:
        return f"{s:.2f} s"
    if s < 3600:
        return f"{s / 60:.1f} min"
    return f"{s / 3600:.2f} h"


def dominant(r: dict[str, str]) -> str:
    share, nit = float(r["hessian_share"]), int(r["nit"])
    if share >= HESSIAN_SHARE:
        return f"Hessian ({share:.0%})"
    if nit > ITER_BOUND:
        return f"iteration count ({nit})"
    return f"per-iteration cost ({r['ms_per_iter']} ms)"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", default=today())
    d = ap.parse_args().date
    mem_p, fit_p = RESULTS / f"memory_{d}.csv", RESULTS / f"memory_fit_{d}.txt"
    wall_p, boot_p = RESULTS / f"wall_{d}.csv", RESULTS / f"bootstrap_{d}.csv"
    tp_p, prof_p = RESULTS / f"throughput_{d}.csv", RESULTS / f"profile_{d}.txt"
    ll_p = RESULTS / "loglik_2026-10-19.csv"
    sim_p = RESULTS / "simulate_2026-10-19.csv"
    out: list[str] = []
    w = out.append

    w(f"# Capability table, {d}\n")
    w(
        "Generated by `benchmarks/capability_report.py` from the CSVs in this directory. "
        "Every figure is from one machine; none is a statement about other hardware.\n"
    )
    w("```")
    out.extend(
        h
        for h in header(wall_p)
        if h.split(":")[0]
        in {
            "date",
            "cpu",
            "logical_cores",
            "ram_gib",
            "os",
            "compiler",
            "python",
            "numpy",
            "hawkes_engine",
        }
    )
    w("```\n")

    # ---- wall ---------------------------------------------------------------
    wall = [r for r in rows(wall_p) if r["status"] == "ok"]
    W = {
        (
            r["M"],
            r["rho_target"],
            0 if int(r["n_events"]) < 2e4 else 1 if int(r["n_events"]) < 2e5 else 2,
        ): r
        for r in wall
    }
    w("## 1. Wall clock of one fit\n")
    w(
        'Pair decay, one start, `se_method="hessian"`, fresh process per run. `reps` is 3 '
        "(median, range) for cells under 30 s and 1 above. The Hessian column is the Hessian "
        "pass timed alone at the fitted point. Dominant-term rule: Hessian if it is at least "
        f"{HESSIAN_SHARE:.0%} of the total; otherwise iteration count if the optimiser needed "
        f"more than {ITER_BOUND} iterations; otherwise per-iteration cost.\n"
    )
    w(
        "| M | rho | events | reps | iters | total | range | ms/iter | Hessian | grad calls "
        "| dominant | label |"
    )
    w("|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|---|---|")
    for r in wall:
        rng = f"{float(r['total_min_s']):.2f}-{float(r['total_max_s']):.2f} s"
        w(
            f"| {r['M']} | {r['rho_target']} | {int(r['n_events']):,} | {r['reps']} | {r['nit']} "
            f"| {fmt_s(float(r['total_s']))} | {rng} | {r['ms_per_iter']} "
            f"| {float(r['hessian_s']):.2f} s | {r['hessian_grad_calls']} | {dominant(r)} "
            f"| {r['reliable']} |"
        )
    w("")
    w(
        "`ms/iter` excludes the Hessian pass. `label` is the library's own reliability label for "
        "that fit; it is a conditioning report, not a bias or coverage statement.\n"
    )

    w("### Largest grid cell finishing under a limit\n")
    w(
        "Per M and rho, the largest N in the grid whose total time was under the limit. The grid "
        'stops at N = 1e6, so "grid ends" means the grid ran out, not that a wall was reached.\n'
    )
    cols = [(m, rho) for m in ("2", "4", "6", "8") for rho in ("0.3", "0.85")]
    w("| limit | " + " | ".join(f"M={m}, rho={rho}" for m, rho in cols) + " |")
    w("|---|" + "--:|" * len(cols))
    for label, lim in (("60 s", 60.0), ("10 min", 600.0), ("1 h", 3600.0)):
        cells = []
        for m, rho in cols:
            ok = [
                int(r["n_events"])
                for r in wall
                if r["M"] == m and r["rho_target"] == rho and float(r["total_s"]) < lim
            ]
            cells.append(
                "none" if not ok else f"{max(ok):,}" + (" (grid ends)" if max(ok) > 9e5 else "")
            )
        w(f"| {label} | " + " | ".join(cells) + " |")
    w("")
    w("Dominant term at the largest N that fits under each limit:\n")
    for label, lim in (("60 s", 60.0), ("10 min", 600.0), ("1 h", 3600.0)):
        parts = []
        for m, rho in cols:
            ok = [
                r
                for r in wall
                if r["M"] == m and r["rho_target"] == rho and float(r["total_s"]) < lim
            ]
            if ok:
                top = max(ok, key=lambda r: int(r["n_events"]))
                parts.append(f"M={m}/rho={rho}: {dominant(top)}")
        w(f"- under {label}: " + "; ".join(parts))
    w("")
    worst = max(wall, key=lambda r: float(r["total_s"]))
    w(
        f"The slowest measured fit is M={worst['M']}, rho={worst['rho_target']}, "
        f"{int(worst['n_events']):,} events: {fmt_s(float(worst['total_s']))}, dominated by "
        f"{dominant(worst)}. No measured cell reached an hour, so the one-hour wall is beyond "
        "this grid and these data do not locate it.\n"
    )
    big = [r for r in wall if int(r["n_events"]) > 9e5 and int(r["M"]) >= 6]
    w(
        "At N = 1e6 and M >= 6: "
        + "; ".join(f"M={r['M']}, rho={r['rho_target']}: {fmt_s(float(r['total_s']))}" for r in big)
        + ".\n"
    )
    small = [r for r in wall if int(r["n_events"]) < 2e4 and int(r["M"]) >= 6]
    w(
        "**Small N at large M is expensive in iterations, not in events.** "
        + "; ".join(
            f"M={r['M']}, rho={r['rho_target']}, {int(r['n_events']):,} events: {r['nit']} "
            f"iterations, {fmt_s(float(r['total_s']))}, label `{r['reliable']}`"
            for r in small
        )
        + ". The optimiser works hardest where the data identify the parameters least.\n"
    )
    w("### The Hessian pass\n")
    calls = sorted({(int(r["M"]), int(r["hessian_grad_calls"])) for r in wall})
    w(
        "Gradient evaluations in the Hessian pass: "
        + ", ".join(f"M={m}: {c} (P={m + 2 * m * m}, {c / (m + 2 * m * m):.1f}P)" for m, c in calls)
        + ". The pass therefore costs a fixed multiple of P gradient evaluations, and each "
        "gradient evaluation costs about M^2 per event (section 5), so its cost grows as M^4 per "
        "event. Share of the fit at N = 1e6, rho = 0.3: "
        + ", ".join(
            f"M={m}: {float(W[(m, '0.3', 2)]['hessian_share']):.0%}" for m in ("2", "4", "6", "8")
        )
        + ".\n"
    )

    # ---- memory -------------------------------------------------------------
    mem = rows(mem_p)
    base_mib = float(next(r for r in mem if r["component"] == "hessian")["base_mib"])
    w("## 2. Memory\n")
    w(
        f"Peak working set of a fresh child process minus the child's peak after imports "
        f"(about {base_mib:.0f} MiB). One start, rho 0.5, pair decay. Median of 3 for N <= 1e5, "
        "single run above.\n"
    )
    w("| M | params | events | events only | optimiser | + Hessian pass |")
    w("|--:|--:|--:|--:|--:|--:|")
    keyed: dict[tuple[str, str], dict[str, dict[str, str]]] = {}
    for r in mem:
        if r["component"] in ("load", "opt", "hessian"):
            keyed.setdefault((r["M"], r["n_events"]), {})[r["component"]] = r
    for (m, n), c in keyed.items():
        w(
            f"| {m} | {c['load']['n_params']} | {int(n):,} "
            f"| {float(c['load']['median_mib']):.2f} MiB "
            f"| {float(c['opt']['median_mib']):.2f} MiB "
            f"| {float(c['hessian']['median_mib']):.2f} MiB |"
        )
    w("")
    gap = max(
        float(c["hessian"]["median_mib"]) - float(c["opt"]["median_mib"]) for c in keyed.values()
    )
    w(
        "`optimiser` includes the event arrays. The Hessian pass adds at most "
        f"{gap:.2f} MiB over the optimiser in any row, with the larger additions at small N and "
        "large M. At N = 1e6 and above it adds nothing measurable.\n"
    )
    boots = [r for r in mem if r["component"].startswith("boot")]
    w("### Bootstrap, one worker's serial share\n")
    w("| M | events | replications | after base fit | after replications | seconds |")
    w("|--:|--:|--:|--:|--:|--:|")
    for r in boots:
        w(
            f"| {r['M']} | {int(r['n_events']):,} | {r['component'].split('_B')[1]} "
            f"| {float(r['min_mib']):.2f} MiB | {float(r['median_mib']):.2f} MiB "
            f"| {float(r['max_mib']):.1f} |"
        )
    w(
        "\nEach pool worker is a separate process with its own interpreter, imports and copy of "
        "the events, so total bootstrap memory is about workers x (import baseline + delta). "
        "That product was not itself measured.\n"
    )

    fit_txt = fit_p.read_text(encoding="utf-8")
    a = float(re.search(r"a_bytes_per_event = ([\d.]+)", fit_txt).group(1))
    b = float(re.search(r"b_bytes_per_param = ([\d.]+)", fit_txt).group(1))
    c0 = float(re.search(r"c_bytes_const\s+= ([\d.]+)", fit_txt).group(1))
    errs = [float(x) for x in re.findall(r"error ([+-][\d.]+)%", fit_txt)]
    w("### Fitted constants\n")
    w(
        "Least squares on the Hessian-mode deltas for N >= 1e5 (seven points, M in 2, 4, 8, N up "
        f"to 1e7): bytes = {a:.1f} * N + {b:.0f} * P + {c0:,.0f}, with P = M + 2M^2 free "
        "parameters.\n"
    )
    w(
        f"The model follows the data: errors range from {min(errs):+.1f}% to "
        f"{max(errs):+.1f}%, the "
        "largest at N = 1e5 where the constant term matters. The per-parameter coefficient is "
        "poorly determined, since P ranges only from 10 to 136 against N over two decades, so it "
        'should not be read as more than "small". The per-event term is the one that matters.\n'
    )
    w("### Largest N under a memory budget\n")
    w(
        f"The budget applies to the whole process: the {base_mib:.0f} MiB import baseline plus the "
        "model. Only N up to 1e7 was measured; larger values extrapolate the fitted line and are "
        "marked.\n"
    )
    w("| budget | largest N (M=2) | largest N (M=8) | basis |")
    w("|--:|--:|--:|---|")
    for gib in (1, 4, 16):
        free = gib * GIB - base_mib * MIB - c0
        n2, n8 = (free - b * 10) / a, (free - b * 136) / a
        w(f"| {gib} GiB | {n2:,.0f} | {n8:,.0f} | {'extrapolated' if n2 > 1.0e7 else 'measured'} |")
    w(
        "\nThe 16 GiB row is allowed by the machine's RAM (see header) but not measured. These "
        "figures exclude holding the caller's own copy of the data and simulating it.\n"
    )

    # ---- bootstrap ----------------------------------------------------------
    w("## 3. What an honest interval costs\n")
    w(
        '`se_method="bootstrap"`: simulate from the fitted model, refit, B times. `workers=0` is '
        "`fit()`'s own default pool (all logical cores). One and four workers call the same "
        "`parametric_bootstrap` directly with `workers` set, because `fit()` does not expose it. "
        "Totals include the base fit and pool start-up. Cells at N = 1e4 are the median of 3, "
        "larger cells a single run.\n"
    )
    w("| M | events | B | workers | total | range | bootstrap alone | per replication |")
    w("|--:|--:|--:|--:|--:|--:|--:|--:|")
    boot = rows(boot_p)
    for r in boot:
        wk = "default" if r["workers"] == "0" else r["workers"]
        bs = fmt_s(float(r["boot_s"])) if r["boot_s"] else "-"
        pr = f"{float(r['boot_s_per_replication']):.3f} s" if r["boot_s_per_replication"] else "-"
        w(
            f"| {r['M']} | {int(r['n_events']):,} | {r['B']} | {wk} | {fmt_s(float(r['total_s']))} "
            f"| {r['min_s']}-{r['max_s']} s | {bs} | {pr} |"
        )
    w("")

    def bt(m: int, n: int, b_: int, wk: int) -> float:
        return next(
            float(r["total_s"])
            for r in boot
            if (r["M"], r["n_events"], r["B"], r["workers"]) == (str(m), str(n), str(b_), str(wk))
        )

    w(
        "Four workers against one at B = 200: "
        + ", ".join(
            f"M={m}, N={n:,}: {bt(m, n, 200, 1) / bt(m, n, 200, 4):.1f}x"
            for m in (2, 4)
            for n in (10000, 100000)
        )
        + ". Default pool against four workers at B = 200: "
        + ", ".join(
            f"M={m}, N={n:,}: {bt(m, n, 200, 4) / bt(m, n, 200, 0):.2f}x"
            for m in (2, 4)
            for n in (10000, 100000)
        )
        + " (above 1 means the default pool is faster).\n"
    )
    hess4 = float(
        next(
            r["total_s"]
            for r in wall
            if r["M"] == "4" and r["rho_target"] == "0.3" and 9e4 < int(r["n_events"]) < 1.1e5
        )
    )
    w(
        f"For scale, the Hessian fit at M=4, N=1e5 takes {fmt_s(hess4)}; "
        f"B = 200 on the default pool "
        f"costs {bt(4, 100000, 200, 0) / hess4:.1f} times that. M=4 at N=1e6 and M >= 6 were not "
        "run with the bootstrap; any figure for them would be an extrapolation and none is given.\n"
    )

    # ---- throughput ---------------------------------------------------------
    w("## 4. Likelihood and simulator throughput\n")
    w(
        "Reused from earlier commits: `loglik_2026-10-19.csv`, `simulate_2026-10-19.csv`. Added "
        "here: M = 6 likelihood, and both simulators at rho = 0.85 for M in 2, 4, 6, 8.\n"
    )
    ll, tp = rows(ll_p), rows(tp_p)

    def ll_med(kernel: str, work: str, m: int, n: int) -> float | None:
        for r in ll:
            if (r["implementation"], r["kernel"], r["work"], r["M"], r["N"]) == (
                "hawkes-engine",
                kernel,
                work,
                str(m),
                str(n),
            ):
                return float(r["median_s"])
        for r in tp:
            if (r["kernel_or_method"], r["what"], r["M"], r["N"]) == (
                kernel,
                f"loglik_{work}",
                str(m),
                str(n),
            ):
                return float(r["median_s"])
        return None

    w("### Pair against shared decay, as measured\n")
    w("Median per call and the ratio pair / shared at the same M, N and work.\n")
    w("| M | N | work | pair | shared | ratio |")
    w("|--:|--:|---|--:|--:|--:|")
    for m in (2, 4, 6, 8):
        for n in (100000, 1000000):
            for work in ("value", "value+grad"):
                p, s = ll_med("pair", work, m, n), ll_med("shared", work, m, n)
                if p and s:
                    w(
                        f"| {m} | {n:,} | {work} | {p * 1000:.1f} ms | {s * 1000:.1f} ms "
                        f"| {p / s:.1f}x |"
                    )
    w(
        "\nThis is a likelihood-call ratio. A fit-level speedup for shared decay was not measured, "
        "and shared decay is a different model (M decay rates, not M^2).\n"
    )
    w("### Simulators\n")
    w("| method | M | rho | events | events/s | ns/event | source |")
    w("|---|--:|--:|--:|--:|--:|---|")
    for r in rows(sim_p):
        n, sec = int(r["events"]), float(r["seconds"])
        w(
            f"| {r['method']} | {r['M']} | {r['rho']} | {n:,} | {n / sec:,.0f} "
            f"| {sec / n * 1e9:.0f} | 2026-10-19 |"
        )
    for r in tp:
        if r["what"] == "simulate":
            n, sec = int(r["N"]), float(r["median_s"])
            w(
                f"| {r['kernel_or_method']} | {r['M']} | {r['rho']} | {n:,} | {n / sec:,.0f} "
                f"| {sec / n * 1e9:.0f} | {d} |"
            )
    w("")

    # ---- profile ------------------------------------------------------------
    w("## 5. Hot loop\n")
    w(
        f"`benchmarks/profile_hotloop.py`, full output in `profile_{d}.txt`. Profiler: cProfile "
        "(Python level) plus a timing decomposition across M. No native sampling profiler was "
        "available (no administrator rights for `wpr`, no Visual Studio profiler), so this is "
        "attribution by measurement and not an instruction-level profile.\n"
    )
    prof = prof_p.read_text(encoding="utf-8")
    w("```")
    out.extend(
        ln
        for ln in prof.splitlines()
        if "{built-in" in ln
        or ln.startswith(("ncalls", "   ncalls", "M  "))
        or re.match(r"^\d  ", ln)
        or ln.startswith("numpy np.exp")
    )
    w("```\n")
    w(
        "Outcome: **measured, nothing to fix; no code was changed.** Nearly all of a fit is inside "
        "the two compiled calls, so Python overhead is not a target. Per event the compiled cost "
        "grows as M^2 and flattens to a few ns per cell, which is the cost of one `exp` per cell "
        "per event that pair decay needs, since every cell has its own rate and every gap "
        "differs. The loop in `cpp/src/workspace.cpp` allocates and copies nothing per event. What "
        "remains is a vectorised `exp` or `-march=native`; ADR-006 rules out the second for "
        "published wheels and the first is not a cheap, safe change, so it is not made here.\n"
    )

    # ---- limits -------------------------------------------------------------
    w("## 6. What the library cannot do at a practical size on this machine\n")
    w(
        f"- A single fit with a Hessian at M = 8, N = 1e6 takes "
        f"{fmt_s(float(W[('8', '0.3', 2)]['total_s']))} "
        f"(rho 0.3) and {fmt_s(float(W[('8', '0.85', 2)]['total_s']))} (rho 0.85); "
        f"at M = 6 it takes "
        f"{fmt_s(float(W[('6', '0.3', 2)]['total_s']))} and "
        f"{fmt_s(float(W[('6', '0.85', 2)]['total_s']))}. "
        "That is a documented cost, not a defect."
    )
    w(
        f"- A bootstrap interval at M = 4, N = 1e5, B = 200 takes "
        f"{fmt_s(bt(4, 100000, 200, 1))} on one "
        f"worker and {fmt_s(bt(4, 100000, 200, 0))} on the default pool. "
        f"Larger configurations were "
        "not timed."
    )
    w(
        "- The Hessian pass costs a fixed 4P gradient evaluations, so its absolute time grows with "
        "M (section 1). Its share of the fit falls at M = 8, where the iteration count dominates "
        "instead."
    )
    w(
        "- At M >= 6 with about 1e4 events, fits finish but are labelled `marginal` or "
        "`unreliable` by the library (section 1). Time is not the limit there; identifiability is."
    )
    w(
        "- Nothing above N = 1e6 was timed, and no cell reached an hour: the upper wall is "
        "not located."
    )
    w("- Memory does not bind below N = 1e7 on this machine.\n")
    w("## 7. This machine only\n")
    w(
        "One CPU (see header), Windows 11, MSVC build without `-march=native`. Bootstrap times "
        "depend on the core count, and every time depends on background load. Single-run cells "
        "carry no spread. Memory used the Windows working-set counter; the Linux `VmHWM` path is "
        "implemented but was not run here.\n"
    )
    text = "\n".join(out) + "\n"
    dest = RESULTS / f"capability_{d}.md"
    dest.write_text(text, encoding="utf-8")
    print(f"written: {dest} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
